-- Catálogos
CREATE TABLE CAT_ESTADO_PRODUCTO
(
    FN_ESTATUS INT PRIMARY KEY,
    FC_DESCRIPCION VARCHAR(100) NOT NULL
);

CREATE TABLE CAT_CATEGORIA
(
    FN_IDCATEGORIA INT AUTO_INCREMENT PRIMARY KEY,
    FC_CODPREF VARCHAR(5) NOT NULL,
    FC_NOMBRE VARCHAR(100) NOT NULL
);

CREATE TABLE CAT_ROL
(
    FN_IDROL INT PRIMARY KEY,
    FC_NOMBRE VARCHAR(100) NOT NULL
);

CREATE TABLE CAT_ACCION
(
    FN_IDACCION INT PRIMARY KEY,
    FC_NOMBRE VARCHAR(100) NOT NULL
);

-- Tablas de Seguridad y Usuarios
CREATE TABLE ROL_ACCION
(
    FN_IDROL INT,
    FN_IDACCION INT,
    PRIMARY KEY (FN_IDROL, FN_IDACCION),
    FOREIGN KEY (FN_IDROL) REFERENCES CAT_ROL(FN_IDROL),
    FOREIGN KEY (FN_IDACCION) REFERENCES CAT_ACCION(FN_IDACCION)
);

CREATE TABLE USUARIO
(
    FC_IDUSUARIO VARCHAR(20) PRIMARY KEY,
    FC_NOMBRE VARCHAR(100) NOT NULL,
    FC_EMAIL VARCHAR(100) NOT NULL,
    FC_PASSWORD VARCHAR(100) NOT NULL,
    FN_IDROL INT NOT NULL,
    FD_CREACION DATETIME DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (FN_IDROL) REFERENCES CAT_ROL(FN_IDROL)
);

-- Tabla SESION actualizada para manejo de JWT y concurrencia
CREATE TABLE SESION
(
    FC_IDSESION VARCHAR(100) PRIMARY KEY,
    FC_IDUSUARIO VARCHAR(20) NOT NULL,
    FC_TOKEN VARCHAR(500) NOT NULL,
    FC_REFRESH_TOKEN VARCHAR(500),
    FC_IP VARCHAR(45),
    FC_USER_AGENT VARCHAR(255),
    FD_CREACION DATETIME DEFAULT CURRENT_TIMESTAMP,
    FD_EXPIRACION DATETIME NOT NULL,
    FN_ESTADO INT(1) DEFAULT 1, -- 1: Activa, 0: Revocada
    FOREIGN KEY (FC_IDUSUARIO) REFERENCES USUARIO(FC_IDUSUARIO)
);

-- Entidad Principal
CREATE TABLE ACTIVO_TECNOLOGICO
(
    FC_IDPRODUCTO VARCHAR(40) PRIMARY KEY,
    FC_FOLIO VARCHAR(16) NOT NULL,
    FC_SERIE VARCHAR(20) NOT NULL,
    FC_MARCA VARCHAR(100) NOT NULL,
    FN_ESTATUS INT NOT NULL,
    FN_COSTO DECIMAL(10, 2) NOT NULL,
    FD_CREACION DATETIME DEFAULT CURRENT_TIMESTAMP,
    FN_IDCATEGORIA INT,
    FOREIGN KEY (FN_IDCATEGORIA) REFERENCES CAT_CATEGORIA(FN_IDCATEGORIA),
    FOREIGN KEY (FN_ESTATUS) REFERENCES CAT_ESTADO_PRODUCTO(FN_ESTATUS)
);

-- Creación de Índices
CREATE INDEX IDX_ACTIVO_FOLIO ON ACTIVO_TECNOLOGICO(FC_FOLIO);
CREATE INDEX IDX_ACTIVO_SERIE ON ACTIVO_TECNOLOGICO(FC_SERIE);
CREATE INDEX IDX_ACTIVO_CATEGORIA ON ACTIVO_TECNOLOGICO(FN_IDCATEGORIA);

-- Tablas Bitácoras
CREATE TABLE HISTORIAL_ESTADO
(
    FN_IDHISTORIAL INT AUTO_INCREMENT PRIMARY KEY,
    FC_IDPRODUCTO VARCHAR(40) NOT NULL,
    FN_ESTADO_ANTERIOR INT,
    FN_ESTADO_NUEVO INT NOT NULL,
    FC_IDUSUARIO VARCHAR(20) NOT NULL,
    FD_FECHA DATETIME DEFAULT CURRENT_TIMESTAMP,
    FC_COMENTARIOS VARCHAR(500),
    FOREIGN KEY (FC_IDPRODUCTO) REFERENCES ACTIVO_TECNOLOGICO(FC_IDPRODUCTO),
    FOREIGN KEY (FN_ESTADO_ANTERIOR) REFERENCES CAT_ESTADO_PRODUCTO(FN_ESTATUS),
    FOREIGN KEY (FN_ESTADO_NUEVO) REFERENCES CAT_ESTADO_PRODUCTO(FN_ESTATUS),
    FOREIGN KEY (FC_IDUSUARIO) REFERENCES USUARIO(FC_IDUSUARIO)
);

CREATE TABLE BITACORA
(
    FN_IDBITACORA INT AUTO_INCREMENT PRIMARY KEY,
    FC_IDUSUARIO VARCHAR(20) NOT NULL,
    FN_IDACCION INT NOT NULL,
    FD_FECHA DATETIME DEFAULT CURRENT_TIMESTAMP,
    FC_DESCRIPCION VARCHAR(500),
    FOREIGN KEY (FC_IDUSUARIO) REFERENCES USUARIO(FC_IDUSUARIO),
    FOREIGN KEY (FN_IDACCION) REFERENCES CAT_ACCION(FN_IDACCION)
);

-- Vista para consulta de activos tecnológicos
CREATE VIEW v_activos_tecnologicos AS
SELECT 
    AT.FC_IDPRODUCTO,
    AT.FC_FOLIO,
    AT.FC_SERIE,
    AT.FC_MARCA,
    EP.FC_DESCRIPCION AS ESTADO,
    AT.FN_COSTO,
    AT.FD_CREACION,
    C.FC_CODPREF,
    C.FC_NOMBRE AS CATEGORIA
FROM ACTIVO_TECNOLOGICO AT
    JOIN CAT_ESTADO_PRODUCTO EP ON AT.FN_ESTATUS = EP.FN_ESTATUS
    JOIN CAT_CATEGORIA C ON AT.FN_IDCATEGORIA = C.FN_IDCATEGORIA;

